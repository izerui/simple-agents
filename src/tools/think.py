"""Research Tools.

工具调用思考
"""

from langchain_core.tools import tool


@tool(parse_docstring=True)
def think_tool(reflection: str) -> str:
    """用于任务理解、复杂度判断和执行前决策的思考工具。

    在任务开始时、准备执行前、遇到分支决策时、获得新信息后或结束前使用此工具，
    用于梳理目标、评估信息缺口、判断复杂度，并确定下一步行动。
    这是一个决策与反思工具，不等同于待办管理工具，也不能替代最终交付。

    何时使用：
    - 任务开始时：我需要先明确目标、约束和已有信息吗？
    - 准备执行前：我现在应该直接做，还是先补信息/换路径？
    - 遇到分支决策时：哪条路线更稳妥、更高效、更符合目标？
    - 获得新信息后：这些信息是否足以继续推进或完成回答？
    - 判断复杂度时：这个任务是否需要使用 `write_todos` 做持续跟踪？
    - 结束前：我现在能直接交付结果，还是仍有关键缺口？

    反思应尽量覆盖：
    1. 任务目标 - 我真正要解决的问题是什么？
    2. 已知信息 - 我已经掌握了哪些事实、资源或上下文？
    3. 信息缺口 - 还缺少哪些关键内容？
    4. 复杂度判断 - 这是可一次完成的任务，还是需要持续进度管理？
    5. 待办决策 - 是否需要使用 `write_todos`，如果需要，原因是什么？
    6. 下一步动作 - 我接下来最合适的具体行动是什么？

    Args:
        reflection: 您对任务目标、已知信息、缺口、复杂度判断以及下一步动作的详细思考

    Returns:
        确认思考内容已记录，可据此继续决策与执行
    """
    return f"{reflection}"
