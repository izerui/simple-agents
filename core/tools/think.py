"""Research Tools.

工具调用思考
"""

from langchain_core.tools import tool


@tool(parse_docstring=True)
def think_tool(reflection: str) -> str:
    """用于研究进度和决策的战略反思工具。

    在每次搜索后使用此工具，系统地分析结果并规划下一步。
    这会在研究工作流中创建一个深思熟虑的暂停，以便做出高质量的决策。

    何时使用：
    - 收到搜索结果后：我找到了哪些关键信息？
    - 决定下一步之前：我是否有足够的信息进行全面回答？
    - 评估研究缺口时：我仍然缺少哪些具体信息？
    - 结束研究之前：我现在能提供完整的答案吗？

    反思应包括：
    1. 当前发现分析 - 我收集了哪些具体信息？
    2. 缺口评估 - 仍然缺少哪些关键信息？
    3. 质量评估 - 我是否有足够的证据/示例来提供好的答案？
    4. 战略决策 - 我应该继续搜索还是提供答案？

    Args:
        reflection: 您对研究进度、发现、缺口和下一步的详细反思

    Returns:
        确认反思已被记录以用于决策
    """
    return f"反思已记录: {reflection}"
